/** Reações: interação real em jsdom, sem rede nem escrita na campanha. */
import {JSDOM} from 'jsdom';
import assert from 'node:assert/strict';
const dom=new JSDOM('<html><body><div id="root"></div></body></html>',{url:'http://localhost',pretendToBeVisual:true});
const globals=globalThis as unknown as Record<string,unknown>;
for(const name of ['window','document','HTMLElement','Element','Node','Event','MouseEvent','KeyboardEvent','localStorage']) globals[name]=name==='window'?dom.window:name==='document'?dom.window.document:(dom.window as unknown as Record<string,unknown>)[name];
globals.IS_REACT_ACT_ENVIRONMENT=true;
globals.fetch=()=>{throw Error('Rede real proibida neste teste')};
const {createElement:h,act}=await import('react');
const {createRoot}=await import('react-dom/client');
const {MovementRiskDialog}=await import('../src/combat/components/MovementRiskDialog');
const {ReactionPanel}=await import('../src/combat/components/ReactionPanel');
const {GridThreatAreas}=await import('../src/combat/grid/GridThreatAreas');
const {CombatHotbar}=await import('../src/combat/components/CombatHotbar');
const {buildCombatHotbarEntries,opportunityHotbarShortcut,buildHotbarSlots}=await import('../src/combat/hotbar');
import type {Attack} from '../src/types';
const host=document.getElementById('root')!,root=createRoot(host);
let checks=0;
const check=(label:string,value:unknown)=>{assert.ok(value,label);checks++;console.log('✔ '+label)};
const click=async(text:string)=>{const button=[...document.querySelectorAll('button')].find(item=>item.textContent?.includes(text));assert.ok(button,text);await act(async()=>button.click())};
const attack:Attack={id:'weapon:fixture',name:'Espada',damage:{count:1,sides:8,bonus:0,type:'Cortante'},extraDamages:[],attackBonus:2,notes:'',ranged:false,finesse:false,legacy:false,reachFeet:5};
try {
 const entries=buildCombatHotbarEntries({attacks:[attack]});
 const waiting=opportunityHotbarShortcut(entries,[attack],false)!;
 check('arma corpo a corpo com alcance gera atalho de reação',waiting.cost==='reaction'&&waiting.label==='Ataque de oportunidade');
 check('arma à distância não inventa oportunidade',!opportunityHotbarShortcut(entries,[{...attack,ranged:true}],false));
 check('ataque sem alcance continua assistido',!opportunityHotbarShortcut(entries,[{...attack,reachFeet:undefined}],false));
 let selected=0;
 const slots=buildHotbarSlots([waiting]).map(slot=>({...slot,ref:null,state:'ready' as const}));
 await act(async()=>root.render(h(CombatHotbar,{slots,busy:false,filter:'reaction',onSelect:()=>selected++})));
 const shortcut=document.querySelector<HTMLButtonElement>('[aria-label*="Ataque de oportunidade"]')!;
 check('filtro Reações exibe ícone aguardando gatilho, sem executar ataque normal',!!shortcut.querySelector('svg')&&shortcut.disabled);
 await act(async()=>shortcut.click());check('atalho aguardando não executa ação',selected===0);
 const pending=opportunityHotbarShortcut(entries,[attack],true)!;
 await act(async()=>root.render(h(CombatHotbar,{slots:buildHotbarSlots([pending]).map(slot=>({...slot,ref:null,state:'ready' as const})),busy:false,onSelect:()=>selected++})));
 await act(async()=>document.querySelector<HTMLButtonElement>('[aria-label*="Ataque de oportunidade"]')!.click());check('atalho ativo encaminha para janela existente',selected===1);
 let answer:boolean|undefined;
 await act(async()=>root.render(h(MovementRiskDialog,{onAnswer:value=>{answer=value}})));
 check('confirmação flutua fora do container do grid',!host.querySelector('[role="alertdialog"]')&&!!document.querySelector('[role="alertdialog"]'));
 check('foco inicial permite rever o caminho',document.activeElement?.textContent==='Rever caminho');
 await click('Rever caminho');check('rever não autoriza movimento',answer===false);
 await click('Continuar');check('continuar autoriza somente a intenção',answer===true);
 let chosen=0,declined=0,visible:boolean|undefined;
 const opportunity={id:'window',reactorUserId:'master',reactorCombatantId:'dragon',trigger:'Herói sai do alcance',sourceCombatantId:'hero',targetCombatantId:'dragon',availableReactions:[{id:'bite',label:'Mordida',description:'Ataque de oportunidade'}],expiresAt:null};
 await act(async()=>root.render(h(ReactionPanel,{opportunity,reactorName:'Dragão',needsVisibility:true,onVisibility:value=>{visible=value},onChoose:()=>chosen++,onDecline:()=>declined++})));
 check('janela identifica o reactor e aparece fora do turno/container',document.querySelector('.reaction-panel h3')?.textContent==='Dragão'&&!host.querySelector('.reaction-panel'));
 check('visão desconhecida impede rolagem antes da adjudicação',document.querySelector<HTMLButtonElement>('.reaction-option')?.disabled);
 await click('Consegue ver');check('Mestre confirma visão pelo callback próprio',visible===true);
 await act(async()=>root.render(h(ReactionPanel,{opportunity,reactorName:'Dragão',onChoose:()=>chosen++,onDecline:()=>declined++})));
 await click('Mordida');await click('Não reagir');check('escolher ou recusar usa os fluxos da reação',chosen===1&&declined===1);
 await act(async()=>root.render(h(GridThreatAreas,{areas:[{minXFeet:30,minYFeet:10,widthFeet:15,heightFeet:15,reachFeet:15}],cellSizeFeet:5,pixelsPerCell:44})));
 const area=document.querySelector<HTMLElement>('.grid-threat-area')!;
 check('aura projeta todo footprint e alcance, sem raio pelo centro',area.style.left==='132px'&&area.style.width==='396px');
 await act(async()=>root.render(h(GridThreatAreas,{areas:[],cellSizeFeet:5,pixelsPerCell:44})));
 check('sem ameaça pública não existe aura',!document.querySelector('.grid-threat-area'));
} finally {await act(async()=>root.unmount());dom.window.close()}
console.log(`${checks} verificações de reação aprovadas.`);
