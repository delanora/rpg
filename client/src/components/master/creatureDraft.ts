import type {
  Creature,
  CreatureKind,
  CreaturePatch,
  Locality,
} from '../../types';
import { ABILITY_KEYS } from '../../dnd';
import {
  mechanicalStateOf,
  deriveConditionEffects,
} from '../../../../src/modules/shared/conditions';
/** Somente prévia do formulário; o servidor recalcula o DTO ao salvar. */
export function creatureDraft(
  kind: CreatureKind,
  locality: Locality,
): Creature {
  const state = mechanicalStateOf({});
  return {
    id: '',
    name: '',
    kind,
    type: '',
    challengeRating: '',
    localities: [{ id: locality.id, name: locality.name }],
    strength: 10,
    dexterity: 10,
    constitution: 10,
    intelligence: 10,
    wisdom: 10,
    charisma: 10,
    hpCurrent: 10,
    hpMax: 10,
    armorClass: 10,
    speed: 9,
    size: 'Medium',
    spatialSize: 'medium',
    effectiveMaxHp: 10,
    effectiveSpeed: 9,
    effectiveArmorClass: 10,
    mechanicalState: state,
    conditionEffects: deriveConditionEffects(state),
    attacks: [],
    derivedAttacks: [],
    inventory: [],
    coins: { cp: 0, sp: 0, ep: 0, gp: 0, pp: 0 },
    spellcastingProfile: {},
    spellcastingResources: { spellSlots: [], pactSlot: null },
    spellRepertoire: { spellIds: [] },
    resistances: [],
    immunities: [],
    vulnerabilities: [],
    description: '',
    imageUrl: '',
    tokenImages: [],
    version: 0,
    createdAt: '',
    updatedAt: '',
    derived: {
      modifiers: Object.fromEntries(
        ABILITY_KEYS.map((a) => [a, 0]),
      ) as Creature['derived']['modifiers'],
    },
  };
}
export function creaturePayload(
  draft: Creature,
): CreaturePatch & { localityIds: string[] } {
  const {
    name,
    kind,
    type,
    challengeRating,
    strength,
    dexterity,
    constitution,
    intelligence,
    wisdom,
    charisma,
    hpCurrent,
    hpMax,
    armorClass,
    speed,
    size,
    attacks,
    abilities,
    spellcastingProfile,
    spellcastingResources,
    spellRepertoire,
    resistances,
    immunities,
    vulnerabilities,
    description,
    imageUrl,
    tokenImages,
  } = draft;
  return {
    name,
    kind,
    type,
    challengeRating,
    strength,
    dexterity,
    constitution,
    intelligence,
    wisdom,
    charisma,
    hpCurrent,
    hpMax,
    armorClass,
    speed,
    size,
    attacks,
    abilities,
    spellcastingProfile,
    spellcastingResources,
    spellRepertoire,
    resistances,
    immunities,
    vulnerabilities,
    description,
    imageUrl,
    tokenImages,
    localityIds: draft.localities.map((l) => l.id),
  };
}
